function inside(poly, x, y) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c;
  }
  return c;
}
const bits = [];
for (let r = 0; r < H; r++) {
  const row = [];
  for (let c = 0; c < W; c++) {
    let n = 0;
    for (let sy = 0; sy < 3; sy++) for (let sx = 0; sx < 3; sx++) {
      const lon = -180 + (c + (sx + 0.5) / 3) * 360 / W, lat = LAT0 - (r + (sy + 0.5) / 3) * (LAT0 - LAT1) / H;
      if (land.some(p => inside(p, lon, lat)) && !water.some(p => inside(p, lon, lat))) n++;
    }
    row.push(n >= 3 ? 1 : 0);
  }
  bits.push(row);
}
